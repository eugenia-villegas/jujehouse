    private ControladorJuego controlador;

    public void setControlador(ControladorJuego controlador) {
        this.controlador = controlador;
    }

    public void actualizarEstado(int oleada, int tranquilidad, int puntaje) {
        lblEstado.setText("Oleada " + oleada + " | Tranquilidad: " + tranquilidad + " | Puntaje: " + puntaje);
    }

    public void mostrarCriaturas(List<Criatura> criaturas) {
        listaCriaturas.setListData(criaturas.toArray(new Criatura[0]));
    }

    public Criatura getCriaturaSeleccionada() {
        return listaCriaturas.getSelectedValue();
    }

    public void agregarInforme(String texto) {
        txtInforme.append(texto + "\n");
    }

    public void mostrarMensaje(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje);
    }

    public void deshabilitarJuego() {
        btnCuchillo.setEnabled(false);
        btnRezo.setEnabled(false);
        btnOfrenda.setEnabled(false);
        btnResolver.setEnabled(false);
    }
    
    public String pedirNombre() {
        String nombre = JOptionPane.showInputDialog(this, "Tu nombre:");
        if (nombre == null || nombre.trim().isEmpty()) {
            return "Jugador";
        }
        return nombre.trim();
    }
    
